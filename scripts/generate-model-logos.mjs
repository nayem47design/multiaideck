// Generates src/components/atoms/ModelLogo/logos.generated.ts: each model's provider logo, brand
// colour and mono (currentColor), from @lobehub/icons-static-svg (MIT, github.com/lobehub/lobe-icons),
// for models the AI logo library lacks (Llama). The same SVG is Figma's Model logo › Model=Llama.
// Run `npm run logos`.
//
// Logos are the providers' trademarks, used to identify which model answered (nominative use).
// Check each brand's guidelines before launch.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const pkgDir = dirname(
  require.resolve("@lobehub/icons-static-svg/package.json"),
);
const { version } = JSON.parse(
  readFileSync(join(pkgDir, "package.json"), "utf8"),
);

// ModelId → [mono icon, colour icon]. Only models without artwork in Figma's AI logo library
// (scripts/generate-ai-logos.mjs) are drawn from here.
const MAP = {
  llama: ["meta", "meta-color"],
};

/** The SVG's inner markup (no <svg>, no <title>), and its viewBox. */
function load(name) {
  const svg = readFileSync(join(pkgDir, "icons", `${name}.svg`), "utf8");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const title = /<title>([^<]*)<\/title>/.exec(svg)?.[1] ?? name;
  const inner = svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<title>[^<]*<\/title>/, "");
  return { viewBox, title, inner };
}

const logos = Object.fromEntries(
  Object.entries(MAP).map(([model, [mono, color]]) => {
    const m = load(mono);
    const c = load(color);
    return [
      model,
      { title: m.title, viewBox: m.viewBox, mono: m.inner, brand: c.inner },
    ];
  }),
);

const out = `// GENERATED by scripts/generate-model-logos.mjs from @lobehub/icons-static-svg@${version} (MIT).
// Do not edit. Provider logos are trademarks of their owners.

import type { ModelId } from "@/lib/ai/models";

export interface ModelLogoArt {
  /** Provider name, e.g. "OpenAI". */
  title: string;
  viewBox: string;
  /** One colour (currentColor). */
  mono: string;
  /** The provider's own colours (same as mono for one-colour marks). */
  brand: string;
}

export const MODEL_LOGOS: Partial<Record<ModelId, ModelLogoArt>> & Record<"llama", ModelLogoArt> = ${JSON.stringify(logos, null, 2)};
`;
writeFileSync(
  join(root, "src/components/atoms/ModelLogo/logos.generated.ts"),
  out,
);
console.log(
  `model logos: ${Object.keys(logos).length} from @lobehub/icons-static-svg@${version}`,
);
