// Generates the AI logo library for the web app from Figma's "AI logo" set (Design system ›
// AI logos, 268:41860): 23 brands × Style (Color, App icon, Black, White), 128×128.
//
//   node scripts/generate-ai-logos.mjs <dir>
//
// <dir> holds Figma's SVG exports, one per variant, named "<brand-slug>--<style-slug>.svg" (e.g.
// "chatgpt--app-icon.svg"). Export them through the Figma bridge (read-only):
//
//   const s = await figma.getNodeByIdAsync("268:41860");
//   return Object.fromEntries(await Promise.all(s.children.map(async (v) =>
//     [v.name, await v.exportAsync({ format: "SVG_STRING" })])));
//
// (export in parallel: sequential exports stall the bridge), then write each value to its file.
//
// Writes public/logos/ai/<brand>--<style>.svg, or .webp (128px) when Figma's artwork is a raster
// (Qwen, Kimi, Cursor, Codex, Gemini's blur): the SVG would carry the full-size bitmap. And
// src/components/atoms/AiLogo/ai-logos.generated.ts, the brands and each file's path.
//
// Logos are trademarks of their owners, used to identify which model answered (nominative use).

import {
  readdirSync,
  readFileSync,
  rmSync,
  mkdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2];
if (!src)
  throw new Error(
    "Usage: node scripts/generate-ai-logos.mjs <dir of Figma SVGs>",
  );

// Figma's Brand values, in the set's order.
const BRANDS = [
  "ChatGPT",
  "Claude",
  "Gemini",
  "Grok",
  "DeepSeek",
  "Kimi",
  "Mistral AI",
  "GLM",
  "MiniMax",
  "Qwen",
  "Perplexity",
  "Codex",
  "Manus",
  "Poe",
  "Microsoft Copilot",
  "Cohere",
  "Stability AI",
  "Hugging Face",
  "Antigravity",
  "Fireworks AI",
  "Cursor",
  "Notion",
  "Apple Intelligence",
];
const STYLES = {
  color: "Color",
  "app-icon": "App icon",
  black: "Black",
  white: "White",
};
const slug = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const out = join(root, "public/logos/ai");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const files = new Set(readdirSync(src));
const manifest = {};
for (const brand of BRANDS) {
  const id = slug(brand);
  manifest[id] = { name: brand, files: {} };
  for (const style of Object.keys(STYLES)) {
    const name = `${id}--${style}.svg`;
    if (!files.has(name)) throw new Error(`Missing ${name} in ${src}`);
    const svg = readFileSync(join(src, name), "utf8");
    let file;
    if (svg.includes("<image")) {
      file = `${id}--${style}.webp`;
      await sharp(Buffer.from(svg), { density: 72 * 2 })
        .resize(128, 128)
        .webp({ quality: 90 })
        .toFile(join(out, file));
    } else {
      file = name;
      writeFileSync(join(out, file), svg.trim() + "\n");
    }
    manifest[id].files[style] = `/logos/ai/${file}`;
  }
}

const ts = `// GENERATED by scripts/generate-ai-logos.mjs from Figma › Design system › AI logos › AI logo
// (268:41860). Do not edit. Logos are trademarks of their owners.

/** Figma's Style values (Color, App icon, Black, White). */
export type AiLogoStyle = ${Object.keys(STYLES)
  .map((s) => JSON.stringify(s))
  .join(" | ")};

export const AI_LOGOS = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<
  string,
  { name: string; files: Record<AiLogoStyle, string> }
>;

export type AiBrand = keyof typeof AI_LOGOS;
`;
writeFileSync(
  join(root, "src/components/atoms/AiLogo/ai-logos.generated.ts"),
  ts,
);
console.log(
  `AI logos: ${BRANDS.length} brands × ${Object.keys(STYLES).length} styles → public/logos/ai`,
);
