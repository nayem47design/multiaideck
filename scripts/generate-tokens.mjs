// Generates the token CSS from the Figma snapshots in src/styles/figma/.
//
//   src/styles/figma/luminous.tokens.json  variables (DTCG), from figma_export_tokens
//   src/styles/figma/luminous.styles.json  Luminous text + effect styles
//
// Outputs (never edit by hand; run `npm run tokens`):
//   src/styles/tokens.css          CSS variables: primitives, Light (:root), Dark ([data-theme="dark"])
//   src/styles/theme.css           Tailwind @theme mapping onto those variables
//   src/styles/typography.css      one utility per Luminous text style
//   src/styles/tokens.generated.ts token list for the Storybook Tokens page

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const stylesDir = join(root, "src/styles");
const variables = JSON.parse(
  readFileSync(join(stylesDir, "figma/luminous.tokens.json"), "utf8"),
);
const styles = JSON.parse(
  readFileSync(join(stylesDir, "figma/luminous.styles.json"), "utf8"),
);

const FILE_KEY = variables.$extensions["figma-console-mcp"].figmaFileKey;
const HEADER = `/*
 * GENERATED by scripts/generate-tokens.mjs — do not edit.
 * Source: Figma file ${FILE_KEY}, Tokens page 28:7489 (snapshots in src/styles/figma/).
 */
`;

// ---------------------------------------------------------------------------
// Read the DTCG tree

/** @returns {{path: string[], token: any}[]} */
function leaves(node, path = []) {
  return Object.entries(node).flatMap(([key, value]) => {
    if (key.startsWith("$")) return [];
    if (value && typeof value === "object" && "$type" in value)
      return [{ path: [...path, key], token: value }];
    return leaves(value, [...path, key]);
  });
}

const collection = (name) => leaves(variables[name]);
const figmaName = (path) => path.join("/");
const cssName = (path) => path.join("-");
const ref = (value) => value.match(/^\{(.+)\}$/)?.[1].split(".");

// Figma's own order (numeric steps ascending), so pages and CSS read like the Figma file.
const step = (s) =>
  /^\d+(-\d+)?$/.test(s) ? Number(s.replace("-", ".")) : NaN;
function byFigmaOrder(a, b) {
  for (let i = 0; i < Math.min(a.path.length, b.path.length); i++) {
    const [x, y] = [a.path[i], b.path[i]];
    if (x === y) continue;
    const [nx, ny] = [step(x), step(y)];
    if (!Number.isNaN(nx) && !Number.isNaN(ny)) return nx - ny;
    return 0;
  }
  return 0;
}

const hex = (value) => {
  const v = value.toLowerCase();
  return v.length === 9 && v.endsWith("ff") ? v.slice(0, 7) : v;
};

// ---------------------------------------------------------------------------
// Primitives: raw colours, never used directly in components.

const primitives = collection("primitives").sort(byFigmaOrder);
const primitiveValue = new Map(
  primitives.map(({ path, token }) => [figmaName(path), hex(token.$value)]),
);
const primitiveVar = (path) => `--primitive-${cssName(path)}`;

// ---------------------------------------------------------------------------
// Semantic colours (Luminous): always an alias of a primitive, per mode.

const semanticGroupOrder = [
  "lum",
  "glass",
  "field",
  "iris",
  "status",
  "overlay",
  "model",
];
const semantic = collection("luminous")
  .map(({ path, token }) => {
    const light = ref(token.$value);
    const dark = ref(
      token.$extensions["figma-console-mcp"].modes?.Dark ?? token.$value,
    );
    if (
      !light ||
      !dark ||
      light[0] !== "primitives" ||
      dark[0] !== "primitives"
    ) {
      throw new Error(
        `${figmaName(path)} must alias a primitive in both modes`,
      );
    }
    const [lightRef, darkRef] = [light.slice(1), dark.slice(1)];
    return {
      path,
      name: figmaName(path),
      cssVar: `--${cssName(path)}`,
      light: {
        primitive: figmaName(lightRef),
        cssVar: primitiveVar(lightRef),
        value: primitiveValue.get(figmaName(lightRef)),
      },
      dark: {
        primitive: figmaName(darkRef),
        cssVar: primitiveVar(darkRef),
        value: primitiveValue.get(figmaName(darkRef)),
      },
    };
  })
  .sort(
    (a, b) =>
      semanticGroupOrder.indexOf(a.path[0]) -
      semanticGroupOrder.indexOf(b.path[0]),
  );

// lum/* drops its prefix in Tailwind (bg-canvas, text-ink-2); other groups keep it (bg-glass-fill).
const twColorName = (path) =>
  (path[0] === "lum" ? path.slice(1) : path).join("-");

// ---------------------------------------------------------------------------
// Dimension and motion

const dimension = collection("luminous-dimension");
const dimensionGroup = (group) =>
  dimension
    .filter(({ path }) => path[0] === group)
    .sort((a, b) => a.token.$value - b.token.$value)
    .map(({ path, token }) => ({
      name: figmaName(path),
      key: path.slice(1).join("-"),
      cssVar: `--${cssName(path)}`,
      value: `${token.$value}px`,
    }));

const space = dimensionGroup("space");
const radius = dimensionGroup("radius");
const size = dimensionGroup("size");
const blur = dimensionGroup("blur");

const motionTokens = collection("luminous-motion");
const motionGroup = (group, unit) =>
  motionTokens
    .filter(({ path }) => path[0] === group)
    .map(({ path, token }) => ({
      name: figmaName(path),
      key: path.slice(1).join("-"),
      cssVar: `--${cssName(path)}`,
      value: `${token.$value}${unit}`,
    }));

const durationOrder = ["instant", "fast", "base", "slow", "ambient"];
const duration = motionGroup("duration", "ms").sort(
  (a, b) => durationOrder.indexOf(a.key) - durationOrder.indexOf(b.key),
);
const easing = motionGroup("easing", "");

// ---------------------------------------------------------------------------
// Effect styles → shadows. Background blur comes from the blur/glass variable.

const round = (n, d = 2) => Number(n.toFixed(d));
const channel = (c) => round(c * 255, 1);
const shadowCss = (effects) =>
  effects
    .filter((e) => e.type === "DROP_SHADOW")
    .map(
      (e) =>
        `${e.offset.x}px ${e.offset.y}px ${e.radius}px ${e.spread}px rgb(${channel(e.color.r)} ${channel(e.color.g)} ${channel(e.color.b)} / ${round(e.color.a)})`,
    )
    .join(", ");

const shadowKey = (name) => {
  const [group, variant] = name.toLowerCase().split("/");
  return group === "elevation"
    ? variant
    : variant === "default"
      ? group
      : `${group}-${variant}`;
};

const shadows = styles.effectStyles.map((s) => {
  const key = shadowKey(s.name);
  const backgroundBlur = s.effects.find((e) => e.type === "BACKGROUND_BLUR");
  return {
    name: s.name,
    key,
    cssVar: `--shadow-${key}`,
    value: shadowCss(s.effects),
    backgroundBlur: backgroundBlur ? `${backgroundBlur.radius}px` : null,
  };
});

const glassBlur = blur.find((b) => b.key === "glass").value;
for (const s of shadows) {
  if (s.backgroundBlur && s.backgroundBlur !== glassBlur) {
    throw new Error(
      `${s.name} background blur ${s.backgroundBlur} does not match blur/glass ${glassBlur}`,
    );
  }
}

// ---------------------------------------------------------------------------
// Text styles

const FONT_FAMILY = {
  Geist: "var(--font-sans)",
  "Geist Mono": "var(--font-mono)",
};
const FONT_WEIGHT = {
  Light: 300,
  Regular: 400,
  Medium: 500,
  SemiBold: 600,
  "Semi Bold": 600,
  Bold: 700,
};

const px = (n) => `${round(n)}px`;
const typography = styles.textStyles
  .filter((s) => s.name.startsWith("Luminous/"))
  .map((s) => {
    if (s.lineHeight.unit !== "PIXELS")
      throw new Error(`${s.name}: expected pixel line height`);
    const letterSpacing =
      s.letterSpacing.unit === "PERCENT"
        ? `${round(s.letterSpacing.value / 100, 4)}em`
        : px(s.letterSpacing.value);
    const fontFamily = FONT_FAMILY[s.fontFamily];
    const fontWeight = FONT_WEIGHT[s.fontStyle];
    if (!fontFamily)
      throw new Error(`${s.name}: no font loaded for ${s.fontFamily}`);
    if (!fontWeight)
      throw new Error(`${s.name}: unknown font style ${s.fontStyle}`);
    const key = s.name
      .slice("Luminous/".length)
      .toLowerCase()
      .replace(/\s+/g, "-");
    return {
      name: s.name,
      utility: `type-${key}`,
      fontFamily,
      figmaFont: `${s.fontFamily} ${s.fontStyle}`,
      fontSize: px(s.fontSize),
      lineHeight: px(s.lineHeight.value),
      fontWeight,
      letterSpacing,
    };
  });

// ---------------------------------------------------------------------------
// Write tokens.css

const decl = (name, value) => `  ${name}: ${value};`;
const block = (selector, lines) => `${selector} {\n${lines.join("\n")}\n}\n`;

const tokensCss = [
  HEADER,
  block(":root", [
    "  /* Primitives: raw values. Never use these in components; use the semantic tokens below. */",
    ...primitives.map(({ path, token }) =>
      decl(primitiveVar(path), hex(token.$value)),
    ),
    "",
    "  /* Dimension · space */",
    ...space.map((t) => decl(t.cssVar, t.value)),
    "",
    "  /* Dimension · radius */",
    ...radius.map((t) => decl(t.cssVar, t.value)),
    "",
    "  /* Dimension · size */",
    ...size.map((t) => decl(t.cssVar, t.value)),
    "",
    "  /* Dimension · blur */",
    ...blur.map((t) => decl(t.cssVar, t.value)),
    "",
    "  /* Effect styles · shadows */",
    ...shadows.map((t) => decl(t.cssVar, t.value)),
    "",
    "  /* Motion */",
    ...duration.map((t) => decl(t.cssVar, t.value)),
    ...easing.map((t) => decl(t.cssVar, t.value)),
    "",
    "  /* Font stacks (the --font-geist-* variables come from next/font). Bangla falls back to",
    "     Noto Sans Bengali inside English text. */",
    decl(
      "--font-sans",
      "var(--font-geist-sans), var(--font-noto-sans-bengali), sans-serif",
    ),
    decl(
      "--font-mono",
      "var(--font-geist-mono), var(--font-noto-sans-bengali), monospace",
    ),
  ]),
  block(':root,\n[data-theme="light"]', [
    "  /* Semantic colour · Light (default) */",
    ...semantic.map((t) => decl(t.cssVar, `var(${t.light.cssVar})`)),
  ]),
  block('[data-theme="dark"]', [
    "  /* Semantic colour · Dark */",
    ...semantic.map((t) => decl(t.cssVar, `var(${t.dark.cssVar})`)),
  ]),
  '/* Figma: "Respect reduced-motion by switching to instant." */',
  `@media (prefers-reduced-motion: reduce) {\n${block(
    ":root",
    duration
      .filter((t) => t.key !== "instant")
      .map((t) => decl(t.cssVar, "var(--duration-instant)")),
  )}}\n`,
].join("\n");

// ---------------------------------------------------------------------------
// Write theme.css (Tailwind). `inline` puts var(--token) straight into each utility, so a
// [data-theme="dark"] subtree (e.g. a Storybook panel) switches theme. `reference` stops
// Tailwind re-emitting these variables: tokens.css owns them, and names such as
// --radius-xl are the same in both, which would otherwise define a variable as itself.

const themeCss = [
  HEADER,
  "@theme inline reference {",
  "  /* Tokens only: remove Tailwind's defaults for every token-backed namespace. */",
  ...[
    "color",
    "spacing",
    "radius",
    "shadow",
    "blur",
    "ease",
    "font",
    "text",
    "font-weight",
    "tracking",
    "leading",
  ].map((ns) => decl(`--${ns}-*`, "initial")),
  "",
  ...semantic.map((t) =>
    decl(`--color-${twColorName(t.path)}`, `var(${t.cssVar})`),
  ),
  decl("--color-transparent", "transparent"),
  decl("--color-current", "currentColor"),
  "",
  ...space.map((t) => decl(`--spacing-${t.key}`, `var(${t.cssVar})`)),
  ...size.map((t) => decl(`--spacing-${t.key}`, `var(${t.cssVar})`)),
  "",
  ...radius.map((t) => decl(`--radius-${t.key}`, `var(${t.cssVar})`)),
  ...shadows.map((t) => decl(`--shadow-${t.key}`, `var(${t.cssVar})`)),
  ...blur.map((t) => decl(`--blur-${t.key}`, `var(${t.cssVar})`)),
  ...easing.map((t) => decl(`--ease-${t.key}`, `var(${t.cssVar})`)),
  "",
  decl("--font-sans", "var(--font-sans)"),
  decl("--font-mono", "var(--font-mono)"),
  "}",
  "",
  "/* Motion durations (Tailwind has no theme namespace for these). */",
  ...duration.map(
    (t) =>
      `@utility duration-${t.key} {\n  transition-duration: var(${t.cssVar});\n}\n`,
  ),
].join("\n");

// ---------------------------------------------------------------------------
// Write typography.css

const typographyCss = [
  HEADER,
  "/* Line heights are absolute pixels, as in Figma. */",
  ...typography.map(
    (t) => `/* ${t.name} · ${t.figmaFont} · ${t.fontSize}/${t.lineHeight} */
@utility ${t.utility} {
  font-family: ${t.fontFamily};
  font-size: ${t.fontSize};
  line-height: ${t.lineHeight};
  font-weight: ${t.fontWeight};
  letter-spacing: ${t.letterSpacing};
}
`,
  ),
].join("\n");

// ---------------------------------------------------------------------------
// Write the token list for Storybook

const manifest = {
  primitives: primitives.map(({ path, token }) => ({
    name: figmaName(path),
    cssVar: primitiveVar(path),
    value: hex(token.$value),
  })),
  colors: semantic.map(({ name, cssVar, path, light, dark }) => ({
    name,
    cssVar,
    utility: twColorName(path),
    light,
    dark,
  })),
  space,
  radius,
  size,
  blur,
  shadows: shadows.map(({ name, key, cssVar, value, backgroundBlur }) => ({
    name,
    key,
    cssVar,
    value,
    backgroundBlur,
  })),
  duration,
  easing,
  typography,
};

const manifestTs = `// GENERATED by scripts/generate-tokens.mjs — do not edit.
// Source: Figma file ${FILE_KEY}, Tokens page 28:7489.

export const tokens = ${JSON.stringify(manifest, null, 2)} as const;
`;

writeFileSync(join(stylesDir, "tokens.css"), tokensCss);
writeFileSync(join(stylesDir, "theme.css"), themeCss);
writeFileSync(join(stylesDir, "typography.css"), typographyCss);
writeFileSync(join(stylesDir, "tokens.generated.ts"), manifestTs);

console.log(
  `tokens: ${primitives.length} primitives, ${semantic.length} semantic colours (Light + Dark), ` +
    `${space.length} space, ${radius.length} radius, ${size.length} size, ${blur.length} blur, ` +
    `${shadows.length} shadows, ${duration.length + easing.length} motion, ${typography.length} text styles`,
);
